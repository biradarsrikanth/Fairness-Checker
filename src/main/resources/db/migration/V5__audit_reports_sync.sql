-- Who did what (audit_log), report export history, PagerDuty sync runs, received webhooks, and the scheduler
-- lock that lets more than one gateway instance run.

-- ---------------------------------------------------------------------------------------------------------
-- audit_log: append-only. The user is kept as plain values (no foreign key), so deleting a user keeps their
-- history and nothing ever has to rewrite a row.
-- ---------------------------------------------------------------------------------------------------------
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- The acting user; null for the system (scheduler) and unknown emails at sign-in
    user_id     BIGINT,
    actor_email VARCHAR(255),
    action      VARCHAR(40)  NOT NULL,
    entity_type VARCHAR(40),
    entity_id   VARCHAR(64),
    details     JSONB,
    ip          VARCHAR(45),
    request_id  VARCHAR(64)
);

CREATE INDEX ix_audit_log_occurred_at ON audit_log (occurred_at DESC);
CREATE INDEX ix_audit_log_user ON audit_log (user_id, occurred_at DESC);
CREATE INDEX ix_audit_log_action ON audit_log (action, occurred_at DESC);

CREATE FUNCTION reject_audit_log_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only';
END
$$;

CREATE TRIGGER trg_audit_log_append_only BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION reject_audit_log_change();

-- ---------------------------------------------------------------------------------------------------------
-- report_export: one row per PDF/Excel download, successful or not
-- ---------------------------------------------------------------------------------------------------------
CREATE TABLE report_export (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       REFERENCES app_user (id) ON DELETE SET NULL,
    report_type  VARCHAR(16)  NOT NULL,
    format       VARCHAR(8)   NOT NULL,
    team_id      BIGINT       REFERENCES team (id) ON DELETE SET NULL,
    engineer_id  BIGINT       REFERENCES engineer_data (id) ON DELETE SET NULL,
    window_start DATE         NOT NULL,
    window_end   DATE         NOT NULL,
    status       VARCHAR(16)  NOT NULL,
    file_name    VARCHAR(255),
    size_bytes   BIGINT,
    duration_ms  INTEGER,
    error        VARCHAR(1000),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_report_type CHECK (report_type IN ('ANALYTICS', 'ENGINEER')),
    CONSTRAINT ck_report_format CHECK (format IN ('PDF', 'XLSX')),
    CONSTRAINT ck_report_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_report_window CHECK (window_end >= window_start),
    CONSTRAINT ck_report_size CHECK (size_bytes IS NULL OR size_bytes >= 0)
);

CREATE INDEX ix_report_export_created_at ON report_export (created_at DESC);
CREATE INDEX ix_report_export_user ON report_export (user_id, created_at DESC);

-- ---------------------------------------------------------------------------------------------------------
-- sync_run: every PagerDuty sync, scheduled or manual ("last synced 4 minutes ago", failures)
-- ---------------------------------------------------------------------------------------------------------
CREATE TABLE sync_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          VARCHAR(16)  NOT NULL,
    trigger_type  VARCHAR(16)  NOT NULL,
    status        VARCHAR(16)  NOT NULL,
    started_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finished_at   TIMESTAMPTZ,
    created_count INTEGER,
    updated_count INTEGER,
    error         VARCHAR(2000),
    -- The admin who started a manual sync
    triggered_by  BIGINT       REFERENCES app_user (id) ON DELETE SET NULL,
    CONSTRAINT ck_sync_kind CHECK (kind IN ('INCIDENTS', 'ONCALLS')),
    CONSTRAINT ck_sync_trigger CHECK (trigger_type IN ('SCHEDULED', 'MANUAL')),
    CONSTRAINT ck_sync_status CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_sync_finished CHECK (finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT ck_sync_counts CHECK (coalesce(created_count, 0) >= 0 AND coalesce(updated_count, 0) >= 0)
);

CREATE INDEX ix_sync_run_kind_started ON sync_run (kind, started_at DESC);

-- ---------------------------------------------------------------------------------------------------------
-- webhook_event: every PagerDuty webhook, stored before it's processed, so the same event is never applied
-- twice and failures can be replayed
-- ---------------------------------------------------------------------------------------------------------
CREATE TABLE webhook_event (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pagerduty_event_id VARCHAR(64)  NOT NULL,
    event_type         VARCHAR(64)  NOT NULL,
    incident_id        VARCHAR(64),
    status             VARCHAR(16)  NOT NULL,
    received_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    processed_at       TIMESTAMPTZ,
    error              VARCHAR(2000),
    payload            JSONB        NOT NULL,
    CONSTRAINT uq_webhook_event UNIQUE (pagerduty_event_id),
    CONSTRAINT ck_webhook_status CHECK (status IN ('RECEIVED', 'PROCESSED', 'IGNORED', 'FAILED'))
);

CREATE INDEX ix_webhook_event_received_at ON webhook_event (received_at DESC);
CREATE INDEX ix_webhook_event_incident ON webhook_event (incident_id);

-- ---------------------------------------------------------------------------------------------------------
-- shedlock: one instance at a time runs each scheduled job (ShedLock's standard table)
-- ---------------------------------------------------------------------------------------------------------
CREATE TABLE shedlock (
    name       VARCHAR(64)  NOT NULL PRIMARY KEY,
    lock_until TIMESTAMP(3) NOT NULL,
    locked_at  TIMESTAMP(3) NOT NULL,
    locked_by  VARCHAR(255) NOT NULL
);
