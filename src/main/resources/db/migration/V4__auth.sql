-- Login accounts, the teams each manager can see, and rotating refresh tokens.
-- Points in time are TIMESTAMPTZ: unlike the alert timestamps, they never need a local-time reading.

-- ---------------------------------------------------------------------------------------------------------
-- app_user: one login; ENGINEER logins are tied to the engineer whose data they see
-- ---------------------------------------------------------------------------------------------------------
CREATE TABLE app_user (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                VARCHAR(255) NOT NULL,
    -- With an algorithm prefix ({bcrypt}...), so the algorithm can change without a migration
    password_hash        VARCHAR(255) NOT NULL,
    full_name            VARCHAR(255) NOT NULL,
    role                 VARCHAR(16)  NOT NULL,
    engineer_id          BIGINT REFERENCES engineer_data (id),
    enabled              BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_login_count   INTEGER      NOT NULL DEFAULT 0,
    locked_until         TIMESTAMPTZ,
    last_login_at        TIMESTAMPTZ,
    password_changed_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_user_role CHECK (role IN ('ADMIN', 'MANAGER', 'ENGINEER')),
    CONSTRAINT ck_user_engineer_link CHECK (role <> 'ENGINEER' OR engineer_id IS NOT NULL),
    CONSTRAINT ck_user_failed_logins CHECK (failed_login_count >= 0),
    -- One login per engineer
    CONSTRAINT uq_user_engineer UNIQUE (engineer_id)
);

CREATE UNIQUE INDEX ux_app_user_email ON app_user (lower(email));

CREATE TRIGGER trg_app_user_updated_at BEFORE UPDATE ON app_user
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------------------------------------
-- user_team_access: the teams a MANAGER can see (ADMINs see every team, ENGINEERs their own)
-- ---------------------------------------------------------------------------------------------------------
CREATE TABLE user_team_access (
    user_id    BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    team_id    BIGINT      NOT NULL REFERENCES team (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, team_id)
);

CREATE INDEX ix_user_team_access_team ON user_team_access (team_id);

-- ---------------------------------------------------------------------------------------------------------
-- refresh_token: opaque, single-use, rotated on every refresh. Only the SHA-256 of the token is stored.
-- Every token descends from one login (family_id); presenting a token that was already rotated revokes the
-- whole family, because it means two parties hold the same token.
-- ---------------------------------------------------------------------------------------------------------
CREATE TABLE refresh_token (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    -- Hex SHA-256; VARCHAR rather than CHAR so Hibernate's schema validation sees a string column
    token_hash     VARCHAR(64)  NOT NULL,
    family_id      UUID         NOT NULL,
    expires_at     TIMESTAMPTZ  NOT NULL,
    revoked_at     TIMESTAMPTZ,
    -- Set when this token was rotated; revoked without a replacement = logged out or revoked
    replaced_by_id BIGINT       REFERENCES refresh_token (id) ON DELETE SET NULL,
    created_ip     VARCHAR(45),
    user_agent     VARCHAR(512),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_refresh_token_expiry CHECK (expires_at > created_at)
);

CREATE INDEX ix_refresh_token_family ON refresh_token (family_id);
CREATE INDEX ix_refresh_token_user ON refresh_token (user_id);
-- Purging expired tokens
CREATE INDEX ix_refresh_token_expires_at ON refresh_token (expires_at);
